import assert from 'node:assert/strict';
import test from 'node:test';
import { createRaid } from '../src/raid/raid.ts';
const map={spawnPoints:[{id:'a',position:[0,0,0],yaw:0}],exits:[],interactions:[{id:'duty-card',label:'duty-card',kind:'loot',item:'service-card',quantity:3,position:[1,1,0]}]};
test('container search reveals one item at a time, resumes, and a rejected transfer preserves the item',()=>{
 const raid=createRaid('a',42,map), same=createRaid('b',42,map);
 assert.deepEqual(raid.containers.get('duty-card'),same.containers.get('duty-card'));
 const source=raid.containers.get('duty-card');
 assert.ok(source.entries.length>=3);
 assert.equal(raid.takeContainerItem('duty-card',source.entries[0].id),false);
 assert.equal(raid.interact('duty-card'),undefined);
 raid.searchContainer('duty-card',.4);
 assert.equal(source.entries.filter(e=>e.revealed).length,0);
 const progress=source.entries[0].progress;
 assert.equal(raid.containers.get('duty-card').entries[0].progress,progress);
 raid.searchContainer('duty-card',source.entries[0].duration-progress+.1);
 assert.equal(source.entries.filter(e=>e.revealed).length,1);
 const entry=source.entries[0];
 assert.equal(raid.takeContainerItem('duty-card',entry.id,{x:6,y:0,rotated:false}),false);
 assert.ok(source.entries.includes(entry));
 assert.equal(raid.takeContainerItem('duty-card',entry.id,{section:'right',x:0,y:0,rotated:true}),true);
 assert.equal(raid.backpack.entries.find(e=>e.item==='service-card').rotated,true);
 assert.equal(raid.takeContainerItem('duty-card',entry.id),false);
 raid.searchContainer('duty-card',20);
 while(raid.backpack.add('salvage',1)) {}
 const remaining=source.entries[0];
 const before=structuredClone(source.entries);
 assert.equal(raid.takeContainerItem('duty-card',remaining.id,{x:0,y:0,rotated:false}),false);
 assert.deepEqual(source.entries,before);
});
